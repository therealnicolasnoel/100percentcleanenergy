import { getCollection, getEntry, type CollectionEntry } from 'astro:content';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import type { Problem } from '../data/problems';

type CuratedNode = CollectionEntry<'nodes'>['data'];
/** A node of the tree: the fixed goal, a curated sub-goal, or a generated step. */
export type MapNode = Omit<CuratedNode, 'type'> & {
  type: 'goal' | 'subgoal' | 'step';
  /** Repo path of the file, or null for generated steps. */
  file: string | null;
  origin: 'fixed' | 'curated' | 'scanner';
  parent?: string;
  keywords?: string[];
  topic?: { id: string; subfield: string | null; field: string | null; works_count: number | null; url: string };
  papers?: number;
};
export interface Project {
  key: string;
  title: string;
  description: string;
  kind: 'open_source' | 'startup' | 'research' | 'user';
  source: string;
  url: string | null;
  subgoal: string;
  step: string | null;
  actors: string[];
  metrics: Record<string, string | number | null>;
  category?: string;
  score: number;
  status?: 'idea' | 'active' | 'paused' | 'done';
  looking_for?: string[];
  contact?: string;
  created_by?: string;
  file?: string;
}
export type Actor = CollectionEntry<'network'>['data'] & { file: string };
export type Kind = Actor['kind'];

export const KIND_LABEL: Record<Kind, string> = {
  builder: 'Building',
  research: 'Research',
  investor: 'Investing',
  funder: 'Funding',
  incubator: 'Incubating',
  policy: 'Policy',
};
export const KINDS = Object.keys(KIND_LABEL) as Kind[];

export const STATUS_LABEL: Record<MapNode['status'], string> = {
  open: 'Open',
  in_progress: 'In progress',
  demonstrated: 'Demonstrated',
  solved: 'Solved',
  impossible: 'Impossible',
};

export interface ProblemData {
  folder: string;
  meta: CollectionEntry<'meta'>['data'] & { file: string };
  root: string;
  nodes: Record<string, MapNode>;
  /** Node ids in depth-first order from the root. */
  order: string[];
  parents: Record<string, string[]>;
  actors: Actor[];
  actorsById: Record<string, Actor>;
  /** Actor ids working on each node. */
  actorsOn: Record<string, string[]>;
  /** Projects under each step or sub-goal: people's own first, then the best scanned. */
  projectsOn: Record<string, Project[]>;
  projects: Project[];
  /** When the step scanner last ran, or null if steps haven't been generated yet. */
  stepsAt: string | null;
}

const repoPath = (p?: string) => (p ?? '').replace(/^\.\//, '');

/**
 * Loads a problem's tree map and network from problems/<slug>/. Returns null
 * when the problem has no keystone.json yet. Throws (failing the build and
 * the pull-request check) when files reference ids that don't exist.
 */
export async function getProblemData(problem: Problem): Promise<ProblemData | null> {
  const folder = problem.slug;
  const metaEntry = await getEntry('meta', folder);
  if (!metaEntry) return null;
  const metaFile = repoPath(metaEntry.filePath) || `problems/${folder}/keystone.json`;
  const warn = (m: string) => console.warn(`[tree] ${m}`);

  // Curated part: the fixed goal and its sub-goals.
  const nodeEntries = (await getCollection('nodes')).filter((e) => e.id.startsWith(`${folder}/`));
  const nodes: Record<string, MapNode> = {};
  for (const e of nodeEntries) {
    const file = repoPath(e.filePath);
    const fileId = e.id.split('/')[1];
    if (e.data.id !== fileId) throw new Error(`${file}: "id" is "${e.data.id}" but the file is named ${fileId}.json. They must match.`);
    // Copy arrays: steps are added below and the collection's data is shared across pages.
    nodes[e.data.id] = { ...e.data, children: [...e.data.children], file, origin: e.data.type === 'goal' ? 'fixed' : 'curated' };
  }
  const root = metaEntry.data.root;
  const r = nodes[root];
  if (!r) throw new Error(`${metaFile}: root "${root}" has no file at problems/${folder}/map/nodes/${root}.json.`);
  if (r.type !== 'goal') throw new Error(`${r.file}: the root must have "type": "goal".`);
  // The problem statement is fixed: it must match the list of 100 problems.
  if (r.title.trim() !== problem.title.trim() && r.title.trim() !== metaEntry.data.title.trim())
    throw new Error(`${r.file}: the goal's title is fixed. It must read "${problem.title}" (set in src/data/problems.ts).`);
  for (const n of Object.values(nodes)) {
    if (n.id === root) continue;
    if (n.type !== 'subgoal') throw new Error(`${n.file}: only the root goal and sub-goals are files. Steps are generated by the step scanner.`);
    if (n.children.length) throw new Error(`${n.file}: a sub-goal can't list children. Steps under it are generated by the step scanner from scan.json.`);
    if (!r.children.includes(n.id)) throw new Error(`${n.file}: sub-goal "${n.id}" isn't listed in the root goal's children (${r.file}).`);
  }
  for (const c of r.children) if (!nodes[c]) throw new Error(`${r.file}: child "${c}" has no file at problems/${folder}/map/nodes/${c}.json.`);

  // Generated part: steps from field/steps.json.
  const stepsFile = join(process.cwd(), 'problems', folder, 'field', 'steps.json');
  let stepsAt: string | null = null;
  if (existsSync(stepsFile)) {
    const d = JSON.parse(readFileSync(stepsFile, 'utf8'));
    stepsAt = d.generated_at;
    for (const st of d.steps as { id: string; parent: string; title: string; description: string; keywords: string[]; topic: MapNode['topic']; papers: number }[]) {
      const parent = nodes[st.parent];
      if (!parent || parent.type !== 'subgoal') { warn(`step ${st.id} points at missing sub-goal "${st.parent}"; skipped`); continue; }
      nodes[st.id] = {
        id: st.id, title: st.title, type: 'step', description: st.description, logic: 'AND', children: [], status: 'in_progress', bottlenecks: [], blocker: false,
        shared_with: [], sources: st.topic ? [{ title: `OpenAlex topic: ${st.title}`, publisher: 'OpenAlex', url: st.topic.url }] : [],
        file: null, origin: 'scanner', parent: st.parent, keywords: st.keywords, topic: st.topic, papers: st.papers,
      };
      parent.children.push(st.id);
    }
  }

  const parents: Record<string, string[]> = {};
  for (const n of Object.values(nodes)) for (const c of n.children) (parents[c] ??= []).push(n.id);
  const order: string[] = [];
  const visit = (id: string) => { order.push(id); for (const c of nodes[id].children) visit(c); };
  visit(root);

  // Curated organisations.
  const actorEntries = (await getCollection('network')).filter((e) => e.id.startsWith(`${folder}/`));
  const actors: Actor[] = actorEntries.map((e) => ({ ...e.data, works_on: [...e.data.works_on], file: repoPath(e.filePath) })).sort((a, b) => a.name.localeCompare(b.name));
  const actorsById = Object.fromEntries(actors.map((a) => [a.id, a]));
  const actorsOn: Record<string, string[]> = {};
  for (const e of actorEntries) {
    const a = actorsById[e.data.id];
    const fileId = e.id.split('/')[1];
    if (a.id !== fileId) throw new Error(`${a.file}: "id" is "${a.id}" but the file is named ${fileId}.json. They must match.`);
    a.works_on = a.works_on.filter((n) => {
      if (nodes[n]) return true;
      // A step a rescan removed shouldn't break the build; the sub-goals are the stable anchor.
      warn(`${a.file}: works_on "${n}" is not a sub-goal or current step; ignored`);
      return false;
    });
    for (const n of a.works_on) (actorsOn[n] ??= []).push(a.id);
    for (const l of a.links) if (!actorsById[l.to]) throw new Error(`${a.file}: link to "${l.to}" has no file at problems/${folder}/network/${l.to}.json.`);
  }

  // Projects: people's own (projects/*.json) and the project scanner's (field/projects.json).
  const projects: Project[] = [];
  for (const e of (await getCollection('projects')).filter((x) => x.id.startsWith(`${folder}/`))) {
    const p = e.data, file = repoPath(e.filePath);
    if (p.id !== e.id.split('/')[1]) throw new Error(`${file}: "id" is "${p.id}" but the file is named ${e.id.split('/')[1]}.json. They must match.`);
    if (nodes[p.subgoal]?.type !== 'subgoal') throw new Error(`${file}: "subgoal" must be one of ${r.children.join(', ')}.`);
    let step = p.step || null;
    if (step && nodes[step]?.parent !== p.subgoal) { warn(`${file}: step "${step}" is not a current step under ${p.subgoal}; shown under the sub-goal`); step = null; }
    projects.push({ key: `user:${p.id}`, title: p.title, description: p.description, kind: 'user', source: 'Created by people', url: p.url ?? p.repo ?? null, subgoal: p.subgoal, step, actors: p.organisations, metrics: {}, score: 1000, status: p.status, looking_for: p.looking_for, contact: p.contact, created_by: p.created_by, file });
  }
  const projFile = join(process.cwd(), 'problems', folder, 'field', 'projects.json');
  if (existsSync(projFile)) {
    for (const p of JSON.parse(readFileSync(projFile, 'utf8')).projects as Project[] & { id: string }[]) {
      const sp = p as Project & { id: string };
      if (nodes[sp.subgoal]?.type !== 'subgoal') continue;
      projects.push({ ...sp, key: sp.id, step: sp.step && nodes[sp.step] ? sp.step : null });
    }
  }
  const projectsOn: Record<string, Project[]> = {};
  for (const p of projects.sort((a, b) => b.score - a.score)) (projectsOn[p.step ?? p.subgoal] ??= []).push(p);

  return { folder, meta: { ...metaEntry.data, file: metaFile }, root, nodes, order, parents, actors, actorsById, actorsOn, projectsOn, projects, stepsAt };
}

/* ---------- Tree layout (left to right) ---------- */

export const TREE = { colW: 300, cardW: 240, pad: 16, gap: 14, h: { goal: 92, subgoal: 92, step: 90, project: 44, more: 30 } };

export interface TreeItem { id: string; kind: 'goal' | 'subgoal' | 'step' | 'project' | 'more'; x: number; y: number; h: number; ref: string; parent: string | null; depth: number }
export interface TreeLayout {
  width: number;
  height: number;
  items: TreeItem[];
  pos: Record<string, TreeItem>;
  edges: { from: string; to: string; or: boolean; first: boolean }[];
}

/**
 * Leaves stack top to bottom; each parent sits level with the middle of its children.
 * With `projects`, each step (and any sub-goal without steps) gets its top projects as
 * a fourth column, plus a "more" item when there are others.
 */
export function layoutTree(d: ProblemData, { projects = false, perStep = 3 } = {}): TreeLayout {
  const items: TreeItem[] = [];
  const edges: TreeLayout['edges'] = [];
  let cursor = TREE.pad;
  let maxDepth = 0;
  const kids = (id: string): { id: string; kind: TreeItem['kind']; ref: string }[] => {
    const n = d.nodes[id];
    const out: { id: string; kind: TreeItem['kind']; ref: string }[] = n.children.map((c) => ({ id: c, kind: d.nodes[c].type, ref: c }));
    if (projects && (n.type === 'step' || n.type === 'subgoal')) {
      const list = d.projectsOn[id] ?? [];
      // A sub-goal's own list only holds projects that fit none of its steps.
      const shown = list.slice(0, perStep);
      out.push(...shown.map((p) => ({ id: `p:${p.key}`, kind: 'project' as const, ref: p.key })));
      if (list.length > perStep) out.push({ id: `more:${id}`, kind: 'more', ref: id });
    }
    return out;
  };
  const walk = (id: string, kind: TreeItem['kind'], ref: string, depth: number, parent: string | null): number => {
    maxDepth = Math.max(maxDepth, depth);
    const h = TREE.h[kind];
    const children = kind === 'project' || kind === 'more' ? [] : kids(id);
    let y: number;
    if (!children.length) {
      y = cursor;
      cursor += h + TREE.gap;
    } else {
      const centres = children.map((c, i) => {
        edges.push({ from: id, to: c.id, or: d.nodes[id]?.logic === 'OR' && c.kind !== 'project' && c.kind !== 'more', first: i === 0 });
        return walk(c.id, c.kind, c.ref, depth + 1, id);
      });
      y = (Math.min(...centres) + Math.max(...centres)) / 2 - h / 2;
    }
    items.push({ id, kind, x: TREE.pad + depth * TREE.colW, y, h, ref, parent, depth });
    return y + h / 2;
  };
  walk(d.root, 'goal', d.root, 0, null);
  const pos = Object.fromEntries(items.map((i) => [i.id, i]));
  return { width: TREE.pad * 2 + maxDepth * TREE.colW + TREE.cardW, height: cursor + TREE.pad, items, pos, edges };
}
