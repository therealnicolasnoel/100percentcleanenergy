import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

/**
 * Everything about a problem lives in one folder, problems/<slug>/:
 *
 *   keystone.json          problem metadata and the map's root (the fixed problem)
 *   map/nodes/<id>.json    the root goal and its curated sub-goals (human-reviewed)
 *   projects/<id>.json     projects people create under a sub-goal or step
 *   network/<id>.json      one file per organisation in the network map
 *   reports/<name>.md      reports
 *
 * Contributors add or edit these files on GitHub; merging to main rebuilds
 * the site. The node format matches ../github-app (keystone.json + map/nodes).
 */

const folder = (entry: string) => entry.split('/')[0];
const fileName = (entry: string) => entry.split('/').pop()!.replace(/\.(md|json)$/, '');

const source = z.object({
  title: z.string(),
  publisher: z.string().optional(),
  year: z.number().int().optional(),
  url: z.url().optional(),
});

const reviewStatus = z.enum(['draft', 'generated', 'reviewed', 'challenged']);

const meta = defineCollection({
  loader: glob({ pattern: '*/keystone.json', base: './problems', generateId: ({ entry }) => folder(entry) }),
  schema: z.object({
    schema: z.number().int().default(1),
    title: z.string(),
    /** Id of the root node in map/nodes/. */
    root: z.string(),
    start_year: z.number().int().optional(),
    review: z
      .object({ map: reviewStatus.default('draft'), network: reviewStatus.default('draft') })
      .default({ map: 'draft', network: 'draft' }),
  }),
});

const nodes = defineCollection({
  loader: glob({
    pattern: '*/map/nodes/*.json',
    base: './problems',
    generateId: ({ entry }) => `${folder(entry)}/${fileName(entry)}`,
  }),
  schema: z.object({
    /** Must match the file name. */
    id: z.string().regex(/^[a-z0-9_]+$/),
    title: z.string(),
    /** Only the fixed goal and its curated sub-goals are files. Steps are generated by
     *  the step scanner (field/steps.json); projects come from the project scanner and
     *  from projects/. */
    type: z.enum(['goal', 'subgoal']),
    description: z.string().optional(),
    /** AND: every child is required. OR: any one child is enough. */
    logic: z.enum(['AND', 'OR']).default('AND'),
    children: z.array(z.string()).default([]),
    status: z.enum(['open', 'in_progress', 'demonstrated', 'solved', 'impossible']).default('open'),
    bottlenecks: z.array(z.enum(['Cost', 'Capital', 'Regulation', 'Supply', 'Knowledge', 'Coordination', 'Talent', 'Demand'])).default([]),
    /** Marks one of the steps that most limits progress today. */
    blocker: z.boolean().default(false),
    /** Sub-goals: years from the problem's start_year to completion without the tracked
     *  projects (P10–P90), and the chance it can be done at all. An assumption people
     *  own; the simulator's main input. */
    estimate: z.object({ p10: z.number().positive(), p90: z.number().positive(), p_success: z.number().min(0).max(1) }).optional(),
    /** How strongly extra effort speeds this sub-goal up (0 = not at all, 0.5 = a lot). Default 0.3. */
    elasticity: z.number().min(0).max(1).optional(),
    /** Another problem number this step is shared with, e.g. 12 for storage. */
    shared_with: z.array(z.number().int().min(1).max(100)).default([]),
    sources: z.array(source).default([]),
  }),
});

const network = defineCollection({
  loader: glob({
    pattern: '*/network/*.json',
    base: './problems',
    generateId: ({ entry }) => `${folder(entry)}/${fileName(entry)}`,
  }),
  schema: z.object({
    id: z.string().regex(/^[a-z0-9_]+$/),
    name: z.string(),
    /** builder: companies and developers. research: labs, universities, data groups.
     *  investor: private capital. funder: public, multilateral and philanthropic money.
     *  incubator: incubators, accelerators and fellowships.
     *  policy: governments, regulators and intergovernmental bodies. */
    kind: z.enum(['builder', 'research', 'investor', 'funder', 'incubator', 'policy']),
    description: z.string(),
    country: z.string().optional(),
    url: z.url().optional(),
    /** Other names the organisation appears under in papers and databases (used by the field scanner). */
    aliases: z.array(z.string()).default([]),
    /** Ids of map nodes this organisation works on. */
    works_on: z.array(z.string()).default([]),
    /** Links to other organisations in the same network folder. */
    links: z
      .array(z.object({ to: z.string(), type: z.enum(['invests_in', 'funds', 'partners', 'supplies', 'regulates']) }))
      .default([]),
    sources: z.array(source).default([]),
  }),
});

const projects = defineCollection({
  loader: glob({
    pattern: '*/projects/*.json',
    base: './problems',
    generateId: ({ entry }) => `${folder(entry)}/${fileName(entry)}`,
  }),
  schema: z.object({
    id: z.string().regex(/^[a-z0-9_]+$/),
    title: z.string().min(3),
    description: z.string(),
    /** The curated sub-goal it serves. Required, so a project survives steps changing. */
    subgoal: z.string(),
    /** A generated step id (for example t10424), if it fits one. */
    step: z.string().optional(),
    url: z.url().optional(),
    repo: z.url().optional(),
    status: z.enum(['idea', 'active', 'paused', 'done']).default('idea'),
    looking_for: z.array(z.string()).default([]),
    /** Organisations involved, by name or curated network id. */
    organisations: z.array(z.string()).default([]),
    contact: z.string().optional(),
    created_by: z.string().optional(),
    created: z.coerce.date().optional(),
  }),
});

const reports = defineCollection({
  loader: glob({
    pattern: '*/reports/*.md',
    base: './problems',
    generateId: ({ entry }) => `${folder(entry)}/${fileName(entry)}`,
  }),
  schema: z.object({
    title: z.string(),
    /** Problem number, 1–100. Must match the folder the file is in. */
    problem: z.number().int().min(1).max(100),
    date: z.coerce.date(),
    updated: z.coerce.date().optional(),
    authors: z.array(z.string()).min(1),
    summary: z.string(),
    status: reviewStatus.default('draft'),
    reviewers: z.array(z.string()).default([]),
    headline: z.object({ value: z.string(), label: z.string() }).optional(),
    confidence: z.enum(['low', 'medium', 'high']).optional(),
    sources: z.array(source).default([]),
    tags: z.array(z.string()).default([]),
  }),
});

export const collections = { meta, nodes, network, projects, reports };
